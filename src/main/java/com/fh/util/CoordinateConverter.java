package com.fh.util;

/**
 * BD-09 墨卡托（MC，米）→ BD-09 经纬度转换。
 *
 * 默认算法为百度官方 MC2LL（分段多项式，系数取自百度地图 JS API），
 * 已用公开样例验证：MC(12958074.255013367, 3572218.8142307573) → BD09(116.4030950, 30.7029839)。
 * 需求文档中的简化公式是标准 Web Mercator 逆变换，对百度墨卡托纬度偏差可达约 0.14°（约 15 公里），
 * 仅保留作对照（coord.algorithm=simple）。
 */
public final class CoordinateConverter {

    private static final double[] MCBAND = {12890594.86, 8362377.87, 5591021, 3481989.83, 1678043.12, 0};

    private static final double[][] MC2LL = {
        {1.410526172116255e-8, 8.98305509648872e-6, -1.9939833816331, 200.9824383106796, -187.2403703815547,
                91.6087516669843, -23.38765649603339, 2.57121317296198, -0.03801003308653, 17337981.2},
        {-7.435856389565537e-9, 8.983055097726239e-6, -0.78625201886289, 96.32687599759846, -1.85204757529826,
                -59.36935905485877, 47.40033549296737, -16.50741931063887, 2.28786674699375, 10260144.86},
        {-3.030883460898826e-8, 8.98305509983578e-6, 0.30071316287616, 59.74293618442277, 7.357984074871,
                -25.38371002664745, 13.45380521110908, -3.29883767235584, 0.32710905363475, 6856817.37},
        {-1.981981304930552e-8, 8.983055099779535e-6, 0.03278182852591, 40.31678527705744, 0.65659298677277,
                -4.44255534477492, 0.85341911805263, 0.12923347998204, -0.04625736007561, 4482777.06},
        {3.09191371068437e-9, 8.983055096812155e-6, 0.00006995724062, 23.10934304144901, -0.00023663490511,
                -0.6321817810242, -0.00663494467273, 0.03430082397953, -0.00466043876332, 2555164.4},
        {2.890871144776878e-9, 8.983055095805407e-6, -3.068298e-8, 7.47137025468032, -0.00000353937994,
                -0.02145144861037, -0.00001234426596, 0.00010322952773, -0.00000323890364, 826088.5}
    };

    private CoordinateConverter() {
    }

    /** 返回 [lon, lat]（BD-09） */
    public static double[] mcToBd09(double x, double y, boolean official) {
        if (!official) {
            return simpleMercatorToLngLat(x, y);
        }
        double[] c = null;
        for (int i = 0; i < MCBAND.length; i++) {
            if (Math.abs(y) >= MCBAND[i]) {
                c = MC2LL[i];
                break;
            }
        }
        if (c == null) {
            c = MC2LL[MC2LL.length - 1];
        }
        double lon = c[0] + c[1] * Math.abs(x);
        double b = Math.abs(y) / c[9];
        double lat = c[2] + c[3] * b + c[4] * b * b + c[5] * b * b * b
                + c[6] * b * b * b * b + c[7] * b * b * b * b * b + c[8] * b * b * b * b * b * b;
        lon *= (x < 0 ? -1 : 1);
        lat *= (y < 0 ? -1 : 1);
        return new double[]{lon, lat};
    }

    /** 需求文档第七节的简化公式（标准 Web Mercator 逆变换），仅作对照 */
    static double[] simpleMercatorToLngLat(double x, double y) {
        double lon = x / 20037508.34 * 180.0;
        double lat = y / 20037508.34 * 180.0;
        lat = 180.0 / Math.PI * (2 * Math.atan(Math.exp(lat * Math.PI / 180.0)) - Math.PI / 2.0);
        return new double[]{lon, lat};
    }
}
